            <h2>1. Eligibility Criteria for Admission to Ph.D. Program</h2>
            <p><strong>(As per the Ph.D. UGC Regulation 2022, Published 07 November 2022)</strong></p>
            
            <p><strong>(1)</strong> Candidates who have completed:</p>
            <p>i. A 1-year/2-semester master's degree programme after a 4-year/8-semester bachelor’s degree programme or a 2-year/4-semester master’s degree programme after a 3-year bachelor’s degree programme or qualifications declared equivalent to the master’s degree by the corresponding statutory regulatory body, with at least 55% marks in aggregate or its equivalent grade in a point scale wherever grading system is followed or equivalent qualification from a foreign educational institution accredited by an assessment and accreditation agency which is approved, recognized or authorized by an authority, established or incorporated under a law in its home country or any other statutory authority in that country to assess, accredit or assure quality and standards of the educational institution.</p>

            <p>A relaxation of 5% marks or its equivalent grade may be allowed for those belonging to SC/ST/OBC (non-creamy layer)/Differently-Abled, Economically Weaker Section (EWS) and other categories of candidates as per the decision of the Commission from time to time.</p>
            
            <p>Provided that a candidate seeking admission after a 4-year/8-semester bachelor’s degree programme should have a minimum of 75% marks in aggregate or its equivalent grade on a point scale wherever the grading system is followed. A relaxation of 5% marks or its equivalent grade may be allowed for those belonging to SC/ST/OBC (non-creamy layer)/Differently-Abled, Economically Weaker Section (EWS) and other categories of candidates as per the decision of the Commission from time to time.</p>

            <p><strong>(2)</strong> Candidates who have completed the M.Phil. programme with at least 55% marks in aggregate or its equivalent grade in a point scale wherever grading system is followed or equivalent qualification from a foreign educational institution accredited by an assessment and accreditation agency which is approved, recognized or authorized by an authority, established or incorporated under a law in its home country or any other statutory authority in that country to assess, accredit or assure quality and standards of educational institutions, shall be eligible for admission to the Ph.D. programme. A relaxation of 5% marks or its equivalent grade may be allowed for those belonging to SC/ST/OBC (non-creamy layer)/Differently-Abled, Economically Weaker Section (EWS) and other categories of candidates as per the decision of the Commission from time to time.</p>

            <h2>2. Admission Procedure</h2>
            <ul class="commitment-list">
                <li>As per the Ph.D. UGC Regulation 2022 (Published 07 November 2022).</li>
                <li>Applications are invited for admission in Ph.D. Program.</li>
                <li>The applicant should fill the application form and submit it with all desired documents together with the fee in the prescribed manner.</li>
                <li>University will organize a Ph.D. Entrance Test and declare the eligibility list for personal interview.</li>
                <li>The result of the Ph.D. entrance test shall be declared on the University Website.</li>
                <li>Date of personal interview and fee deposition for qualified applicants will be notified through email and uploaded on the website.</li>
                <li>Applicants shall be admitted to the Ph.D. program after deposition of fees and verification of original documents (originals + 2 photocopies each) by the admission department.</li>
            </ul>

            <h2>3. Ph.D. Entrance Test</h2>
            <ul class="commitment-list">
                <li>List of eligible candidates for entrance test will be displayed on the University website.</li>
                <li>Eligible candidates have to appear in the entrance test conducted by the University.</li>
                <li>The entrance test shall be of objective type in nature with total 200 marks and a duration of two hours.</li>
                <li>Successful candidates will be called for a personal interview.</li>
                <li>Applicants shall be shortlisted on the basis of merit for the predetermined seats available in each Department/Faculty/Subject for the Ph.D. program in an academic session.</li>
                <li>The allocation of the supervisor for a selected applicant shall be decided by the University depending on the number of seats per supervisor, available specializations, and research interests of the applicant.</li>
            </ul>

            <h2>4. Scheme & Syllabus for Entrance Test</h2>
            <p>There shall be one session of two hours duration. Applicants will be required to attempt the following two papers:</p>
            
            <p><strong>a. Paper I</strong> — Common for all applicants of various disciplines, carrying 100 marks, one-hour duration. There will be 50 objective-type questions based on research methodology which include:</p>
            <ul class="commitment-list">
                <li>General awareness: 15 questions</li>
                <li>Basic computers: 15 questions</li>
                <li>Research Aptitude: 10 questions based on reasoning and statistics</li>
                <li>Research Methodology: 10 questions</li>
            </ul>

            <p><strong>b. Paper II</strong> — Based on the individual’s subject/discipline to which the applicant belongs. The paper will be of 100 marks for one hour duration. There will be 50 subjective (objective type) questions.</p>

            <p><strong>c. Passing marks:</strong> 50% in both papers.</p>
