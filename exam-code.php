        <h2>Examination Guidelines</h2>

        <h3>Code for Invigilators</h3>
        <ul>
            <li>Report to Centre Superintendent 30 minutes before exam on first day and 20 minutes on subsequent days.</li>
            <li>Count answer books and verify number of candidates.</li>
            <li>Reach exam hall 15 minutes prior and ensure no unauthorized material.</li>
            <li>Allow students entry only after invigilator arrival.</li>
            <li>Distribute answer books 10 minutes before exam only to seated candidates.</li>
            <li>Distribute question papers only after commencement bell.</li>
            <li>No candidate allowed to leave before first two hours.</li>
            <li>Verify admit card, roll number, attendance signatures.</li>
            <li>Remain alert; supply graph sheets/material when required.</li>
            <li>Prevent unfair means strictly.</li>
            <li>Escort toilet visits properly.</li>
            <li>No reading, chatting, or unrelated activities.</li>
            <li>No unauthorized persons inside exam hall.</li>
            <li>Smoking/tobacco strictly prohibited.</li>
            <li>Collect answer books after final bell and submit properly.</li>
        </ul>

        <h3>Important Duties</h3>
        <ul>
            <li>Check answer book entries and signatures.</li>
            <li>Take attendance signatures.</li>
            <li>Match photo/signature with admission card.</li>
            <li>Complete invigilator statement.</li>
        </ul>

        <h3>Flying Squad</h3>
        <ul>
            <li>Appointed team of minimum three teachers (including one lady).</li>
            <li>Maintain discipline around exam centre.</li>
            <li>Visit exam halls frequently.</li>
            <li>Search suspected candidates.</li>
            <li>Seize unfair material if found.</li>
            <li>Report malpractice cases immediately.</li>
        </ul>

        <h3>Code for Students</h3>
        <ul>
            <li>Write clearly on ruled lines and avoid wasting pages.</li>
            <li>Fill cover page entries carefully.</li>
            <li>No mobile phones or programmable calculators.</li>
            <li>Arrive before exam; late entry after 30 minutes not allowed.</li>
            <li>Occupy allotted seat only.</li>
            <li>Use blue/black ink only.</li>
            <li>No writing on question paper or admit card.</li>
            <li>Strict action against unfair means.</li>
            <li>No smoking or intoxicants.</li>
        </ul>

        <h3>Policy for Persons with Disabilities</h3>
        <ul>
            <li>Scribe facility for candidates with 40%+ disability.</li>
            <li>Compensatory time minimum 20 minutes per hour.</li>
            <li>Assistive devices allowed where applicable.</li>
            <li>Accessible formats like Braille/large print/computer.</li>
        </ul>

        <h3>Candidates with Injury</h3>
        <ul>
            <li>Amanuensis allowed on valid medical certificate.</li>
            <li>Extra time may be granted.</li>
            <li>Computer allowed without internet where applicable.</li>
        </ul>

